export function buildReportEvidencePrompt(myeongsik: Myeongsik): string {
  const { facts } = deriveInterpretationFacts(myeongsik);
  return `아래 확정 근거만 사용해 ${myeongsik.fortune.targetYear}년 사주 편지를 작성해. 계산된 사실과 네가 덧붙이는 일상어 풀이를 구분하고, 근거에 없는 사주 용어·관계·사건은 절대 넣지 마.

확정 근거:
${formatFacts(facts)}`;
}
