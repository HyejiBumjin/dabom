export const REPORT_PROMPT_VERSION = "essay-v7-deterministic-facts";

function formatFacts(facts: InterpretationFact[]) {
  return facts.map((fact, index) => [
    `근거 ${index + 1}. ${fact.title}`,
    `- 계산 설명: ${fact.description}`,
    ...(fact.writingGuidance ? [`- 허용된 풀이 관점: ${fact.writingGuidance}`] : []),
    ...fact.evidence.map((evidence) => `- 원본 근거: ${evidence}`),
  ].join("\n")).join("\n\n");
}

